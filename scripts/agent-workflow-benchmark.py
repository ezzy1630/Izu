#!/usr/bin/env python3
"""Compare two actual agent tasks on the real izu-merge crate using Git and Izu.

All mutations are in new owned fixtures. No remote or primary checkout writes.
This small workload reports observations; it does not assert a winning backend.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from contextlib import ExitStack
import hashlib
import json
import os
from pathlib import Path
import runpy
import shutil
import subprocess
import sys
import tempfile
import time


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--izu", type=Path, required=True)
    parser.add_argument("--codex", type=Path, required=True)
    parser.add_argument("--auth-file", type=Path, required=True)
    parser.add_argument("--cargo-wrapper", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--backends", nargs="+", choices=("git", "izu"), default=["git", "izu"])
    args = parser.parse_args()
    scripts = Path(__file__).resolve().parent
    source = scripts.parent
    host = runpy.run_path(str(scripts / "agent-host.py"))
    output = host["require_local"](args.output)
    output.mkdir(mode=0o700, parents=True, exist_ok=False)
    izu, codex, wrapper = (str(p.resolve(strict=True)) for p in (args.izu, args.codex, args.cargo_wrapper))
    records = []
    environment = os.environ.copy()
    environment.update(IZU_AUTHOR_NAME="Workflow fixture", IZU_AUTHOR_EMAIL="fixture@example.invalid",
                       GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL="/dev/null", PYTHONDONTWRITEBYTECODE="1")
    baseline = output / "source"; baseline.mkdir()
    for directory in ("src", "tests"):
        shutil.copytree(source / "crates/izu-merge" / directory, baseline / directory)
    (baseline / "Cargo.toml").write_text('[package]\nname="izu-merge"\nversion="0.1.0"\nedition="2024"\n[workspace]\n[dependencies]\n')
    (baseline / ".gitignore").write_text(".artifacts/\ntarget/\n")
    (baseline / "Cargo.lock").write_text('# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "izu-merge"\nversion = "0.1.0"\n')
    original = {str(p.relative_to(baseline)): sha(p) for p in baseline.rglob("*") if p.is_file()}
    tasks = [
        ("diff", "Add tests/agent_diff.rs containing three Rust regression tests named agent_diff_empty, agent_diff_no_newline, agent_diff_unicode. Use public diff and apply_patch APIs to assert exact reconstruction for empty input, a changed final line without a trailing newline, and multibyte UTF-8. Read the API and existing tests first. Add substantive assertions. Change only tests/agent_diff.rs."),
        ("merge", "Add tests/agent_merge.rs containing three Rust regression tests named agent_merge_nonoverlap, agent_merge_delete_modify, agent_merge_add_add. Assert the exact clean result for nonoverlapping line edits, and the correct conflict kind and alternatives for delete/modify and add/add. Read the API and existing tests first. Add substantive assertions. Change only tests/agent_merge.rs.")]
    results = []

    def run(label, command, cwd, env=None, timeout=600):
        # Labels are unique per phase and task, so parallel writers own separate logs.
        start = time.monotonic()
        code = None
        with (output / (label + ".stdout")).open("xb") as out, (output / (label + ".stderr")).open("xb") as err:
            process = subprocess.Popen(command, cwd=cwd, env=env or environment,
                                       stdin=subprocess.DEVNULL, stdout=out, stderr=err, start_new_session=True)
            try:
                code = process.wait(timeout=timeout)
            finally:
                try:
                    host["settle_owned"](process, group=True)
                finally:
                    records.append({"phase": label, "argv": command, "cwd": str(cwd),
                                    "seconds": time.monotonic()-start, "exit": code,
                                    "cleanup_exit": process.poll()})
        if code: raise ValueError(f"{label} failed; inspect retained logs")
        return (output / (label + ".stdout")).read_text()

    def git(label, root, *argv):
        return run(label, ["git", "-c", "user.name=Workflow fixture", "-c", "user.email=fixture@example.invalid", "-c", "core.hooksPath=/dev/null", *argv], root).strip()

    def native(label, root, *argv):
        response = json.loads(run(label, [izu, "--repo", str(root), "--json", *argv], root))
        if response["outcome"]["kind"] != "ok": raise ValueError(f"{label} was not acknowledged")
        return response["outcome"]["result"]["data"]

    try:
        for backend in args.backends:
            began = time.monotonic()
            area = output / backend; area.mkdir()
            root = area / "repository"; shutil.copytree(baseline, root)
            state = area / "state"; state.mkdir(mode=0o700)
            target = area / "build"; target.mkdir()
            check = [wrapper, "cargo", "test", "--offline", "--locked", "--target-dir", str(target)]
            run(backend+"-baseline-check", check, root)
            if backend == "git":
                git("git-init", root, "init", "--initial-branch=main")
                git("git-add-base", root, "add", ".")
                git("git-commit-base", root, "commit", "-m", "Original merge crate")
                git("git-index", root, "config", "core.untrackedCache", "true")
                base = git("git-base", root, "rev-parse", "HEAD")
            else:
                native("izu-init", root, "init", str(root))
                base = native("izu-base", root, "commit", "-m", "Original merge crate")["revision"]
            workspace_paths = {}
            if backend == "git":
                for name, _ in tasks:
                    workspace = area / name
                    git("git-worktree-"+name, root, "worktree", "add", "--detach", str(workspace), base)
                    workspace_paths[name] = workspace

            def agent(task):
                name, prompt = task
                evidence = state / name
                prompt += " Do not use Git or Izu, do not add dependencies, and do not run Cargo; the harness runs the tests and checks your scope after you finish."
                if backend == "izu":
                    command = [sys.executable, str(scripts / "agent-host.py"), "start", "--izu", izu,
                               "--repo", str(root), "--change", name, "--codex", codex,
                               "--state-root", str(state), "--auth-file", str(args.auth_file.resolve()),
                               "--prompt", prompt, "--evidence", str(evidence), "--timeout-seconds", "600", "--evidence-mode", "full"]
                    run("izu-agent-"+name, command, root, timeout=660)
                    binding = json.loads((evidence / "binding.json").read_text())
                    workspace_paths[name] = Path(binding["cwd"])
                else:
                    evidence.mkdir(mode=0o700)
                    (evidence / "prompt.txt").write_text(prompt)
                    with tempfile.TemporaryDirectory(dir=state, prefix="auth-") as temporary:
                        auth = Path(temporary) / "auth.json"
                        with args.auth_file.open("rb") as src, auth.open("xb") as dest:
                            auth.chmod(0o600); shutil.copyfileobj(src, dest)
                        env = environment.copy(); env.update(CODEX_HOME=temporary, TMPDIR=temporary, XDG_CACHE_HOME=temporary)
                        run("git-agent-"+name, [sys.executable, str(scripts / "agent-host.py"), "_child",
                            "--codex", codex, "--evidence", str(evidence), "--model", "gpt-6.1-sol", "--evidence-mode", "full"],
                            workspace_paths[name], env=env, timeout=660)
                observed = json.loads((evidence / "host-result.json").read_text())
                if observed["returncode"] != 0: raise ValueError("agent did not finish")
                workspace = workspace_paths[name]
                for path, digest in original.items():
                    if sha(workspace / path) != digest: raise ValueError(f"agent changed original source: {path}")
                expected = "tests/agent_"+name+".rs"
                binding = json.loads((evidence / "binding.json").read_text())
                added = set(observed["after"]) - set(binding["before"])
                if added != {expected}: raise ValueError(f"agent changed unexpected paths: {added}")
                if not any(json.loads(line).get("type") == "turn.completed" for line in (evidence / "codex-events.jsonl").read_text().splitlines()):
                    raise ValueError("no completed model turn event")
                return name

            with ThreadPoolExecutor(max_workers=2) as pool:
                list(pool.map(agent, tasks))
            current = base
            for name, _ in tasks:
                if backend == "git":
                    workspace = workspace_paths[name]
                    git("git-add-"+name, workspace, "add", "tests/agent_"+name+".rs")
                    git("git-commit-"+name, workspace, "commit", "-m", name)
                    revision = git("git-revision-"+name, workspace, "rev-parse", "HEAD")
                    candidate = area / ("candidate-"+name)
                    git("git-candidate-"+name, root, "worktree", "add", "--detach", str(candidate), current)
                    git("git-merge-"+name, candidate, "merge", "--no-commit", "--no-ff", revision)
                    run("git-check-"+name, check, candidate)
                    git("git-merge-commit-"+name, candidate, "commit", "-m", "Checked candidate "+name)
                    result = git("git-candidate-revision-"+name, candidate, "rev-parse", "HEAD")
                    git("git-land-"+name, root, "update-ref", "refs/heads/main", result, current)
                    current = result
                else:
                    revision = native("izu-commit-"+name, root, "--change", name, "commit", "-m", name)["revision"]
                    candidate = native("izu-candidate-"+name, root, "candidate", revision, "--target", "main",
                        "--expect", current, "--check", "cargo-tests", "--author-name", "Workflow fixture",
                        "--author-email", "fixture@example.invalid", "--", *check)["Ready"]["candidate"]
                    native("izu-check-"+name, root, "check", candidate, "--check", "cargo-tests")
                    current = native("izu-land-"+name, root, "land", candidate)["revision"]
            if backend == "git":
                # Main's worktree was deliberately left at the original source during checked publication.
                git("git-materialize", root, "reset", "--hard", current)
            else:
                native("izu-materialize", root, "update")
            listing = run(backend+"-final-list", check+["--", "--list"], root)
            for test in ["agent_diff_empty", "agent_diff_no_newline", "agent_diff_unicode",
                         "agent_merge_nonoverlap", "agent_merge_delete_modify", "agent_merge_add_add"]:
                if test+": test" not in listing: raise ValueError("missing required test "+test)
            run(backend+"-final-check", check, root)
            for path, digest in original.items():
                if sha(root / path) != digest: raise ValueError("integrated original source differs")
            hashes = {name: sha(root / ("tests/agent_"+name+".rs")) for name, _ in tasks}
            for name, _ in tasks:
                if sha(workspace_paths[name] / ("tests/agent_"+name+".rs")) != hashes[name]:
                    raise ValueError("integration changed agent output")
            elapsed = time.monotonic()-began
            results.append({"backend":backend,"accepted_tasks":2,"wall_seconds":elapsed,
                "manual_interventions":0,"source_hashes":hashes,"final_revision":current})
    finally:
        report = {"izu_sha256":sha(izu),"codex_sha256":sha(codex),"driver_sha256":sha(__file__),
                  "source":original,"results":results,"commands":sorted(records,key=lambda row:row["phase"]),
                  "limitations":["One small real-crate workload; model latency and caches are uncontrolled.",
                  "Both backends test the exact candidate and lease main; durability contracts differ.",
                  "Fixtures and logs retained for independent inspection; cleanup is not included."]}
        (output / "report.json").write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps(results,indent=2))


if __name__ == "__main__":
    main()
